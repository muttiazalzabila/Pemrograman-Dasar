# 1. Integer → angka bulat
jumlah_siswa = 30

# 2. Float → angka desimal
nilai_rata_rata = 85.75

# 3. String → teks
nama_kelas = "Sistem Informasi A"

print("=== TIPE DATA UTAMA ===")
print("Integer :", jumlah_siswa)
print("Float   :", nilai_rata_rata)
print("String  :", nama_kelas)

print("\n=== CEK TIPE DATA ===")
print("Tipe jumlah_siswa   =", type(jumlah_siswa))
print("Tipe nilai_rata_rata =", type(nilai_rata_rata))
print("Tipe nama_kelas      =", type(nama_kelas))
